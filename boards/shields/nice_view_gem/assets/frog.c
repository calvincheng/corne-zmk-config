/*
 * Frog display art for the nice!view "gem" (right / peripheral) screen.
 *
 * Pixel art: glooo89 -- "1-bit a frog set"
 *   https://glooo89.itch.io/1-bit-a-frog-set
 *
 * The art is derived from the "1bit-monitor-glow" (default / white frog on a
 * dark background) sprites that ship with the set. Sprites are extracted from
 * the 16x16 "animacion frog_16x16px.png" sheet, upscaled x4 (nearest-neighbor),
 * and laid out as:
 *   frog_idle_*  : idle loop (row 0 of the sheet)
 *   frog_eat_*   : eating action (row 1)
 *   frog_jump_*  : jumping action (row 2)
 *
 * The frame sheet is shifted down so the idle/eat "ground" frames rest on the
 * bottom edge of the display; the jump frames still rise above that baseline.
 *
 * Color mapping: dark source pixels -> the frog, everything else -> background,
 * so the art reads as a white frog on a black panel. The bitmap stores the
 * palette index (1 = index1), so with the default palette (index0 = white,
 * index1 = black) the panel is black (1) and the frog white (0).
 *
 * Format: LV_IMG_CF_INDEXED_1BIT, MSB-first, 8-byte palette, rows byte aligned.
 */
