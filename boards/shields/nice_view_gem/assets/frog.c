/*
 * Frog display art for the nice!view "gem" (right / peripheral) screen.
 *
 * Pixel art: glooo89 -- "1-bit a frog set"
 *   https://glooo89.itch.io/1-bit-a-frog-set
 *
 * The frames are the canonical 16x16 sprites from the set's example
 * animations (example_frog_idle.gif / eat / jump): those files are 160x160
 * renders where each sprite pixel is a 10x10 block, so the real sprites are
 * 16x16. They are extracted here at true pixel size and upscaled x4
 * (nearest-neighbor) onto the display.
 *
 * The nice!view panel is mounted rotated, so art that should read upright is
 * authored pre-rotated (matching the +90 deg compensation the module applies
 * to its text canvases). The intended upright image is the white frog on the
 * panel, resting on the bottom edge; the jump frames rise above that baseline.
 *
 * Bitmap: frog = palette index 1, background = index 0, MSB-first, rows byte
 * aligned. Palette order follows the nice_view convention.
 *
 * Format: LV_IMG_CF_INDEXED_1BIT.
 */
